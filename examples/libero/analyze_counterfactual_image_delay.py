def _write_csv(path: pathlib.Path, rows: list[dict]) -> None:
    if not rows:
        return
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def _copy_with_name(directory: pathlib.Path, source_name: str, target_name: str) -> None:
    source = directory / source_name
    if source.exists():
        shutil.copyfile(source, directory / target_name)


def _load_summary(path: pathlib.Path) -> tuple[pathlib.Path, dict]:
    summary_path = path / "summary.json" if path.is_dir() else path
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    if summary.get("experiment") != EXPERIMENT or summary.get("schema_version") != SCHEMA_VERSION:
        raise ValueError("Requires a counterfactual image-delay summary generated by the matching runner")
    return summary_path, summary


def _mask_rows(summary_path: pathlib.Path, records: list[dict]) -> list[dict]:
    rows = []
    for record in records:
        if record.get("outcome") not in ("success", "failure"):
            continue
        trace_path = summary_path.parent / record["trace_path"]
        with np.load(trace_path, allow_pickle=False) as archive:
            if "mask_stats" not in archive:
                continue
            stats = np.asarray(archive["mask_stats"], dtype=float)
            steps = np.asarray(archive["query_steps"], dtype=int)
        if stats.shape != (len(steps), 4):
            raise ValueError(f"Invalid mask_stats shape in {trace_path}: {stats.shape}")
        for step, values in zip(steps, stats):
            rows.append({
                "condition": record["condition"],
                "repeat_index": record["repeat_index"],
                "step": int(step),
                "current_target_pixels": float(values[0]),
                "delayed_target_pixels": float(values[1]),
                "current_target_visible": bool(values[2]),
                "delayed_target_visible": bool(values[3]),
            })
    return rows


def _plot_mask_visibility(rows: list[dict], directory: pathlib.Path) -> None:
    if not rows:
        return
    import matplotlib
    matplotlib.use("Agg")
    from matplotlib import pyplot as plt

    grouped: dict[str, list[dict]] = collections.defaultdict(list)
    for row in rows:
        grouped[row["condition"]].append(row)
    fig, axes = plt.subplots(2, 1, figsize=(10, 7), sharex=True)
    colours = {condition: plt.get_cmap("tab10")(index) for index, condition in enumerate(CONDITIONS)}
    for condition, condition_rows in grouped.items():
        by_step: dict[int, list[float]] = collections.defaultdict(list)
        by_step_visible: dict[int, list[float]] = collections.defaultdict(list)
        for row in condition_rows:
            by_step[row["step"]].append(row["delayed_target_pixels"])
            by_step_visible[row["step"]].append(float(row["delayed_target_visible"]))
        steps = sorted(by_step)
        axes[0].plot(steps, [np.mean(by_step[step]) for step in steps], color=colours[condition], label=condition)
        axes[1].plot(steps, [np.mean(by_step_visible[step]) for step in steps], color=colours[condition], label=condition)
    axes[0].set_ylabel("Delayed target mask pixels")
    axes[1].set_ylabel("Visible fraction")
    axes[1].set_xlabel("Environment step")
    axes[1].set_ylim(-0.05, 1.05)
    for axis in axes:
        axis.grid(alpha=0.25)
        axis.legend(fontsize=8)
    fig.suptitle("Target-object visibility used by the image compositor")
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig.savefig(directory / "target_mask_visibility.png", dpi=160)
    plt.close(fig)


def _wilson_interval(successes: int, completed: int, z: float = 1.96) -> tuple[float, float]:
    if completed <= 0:
        return float("nan"), float("nan")
    p = successes / completed
    denominator = 1.0 + z * z / completed
    centre = (p + z * z / (2.0 * completed)) / denominator
    radius = z * np.sqrt(p * (1.0 - p) / completed + z * z / (4.0 * completed * completed)) / denominator
    return max(0.0, centre - radius), min(1.0, centre + radius)


def _plot_success_rate(aggregates: list[dict], directory: pathlib.Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    from matplotlib import pyplot as plt

    names = [row["condition"] for row in aggregates]
    rates = [row["success_rate"] if row["success_rate"] is not None else 0.0 for row in aggregates]
    lower, upper = [], []
    for row in aggregates:
        lo, hi = _wilson_interval(row["successes"], row["completed"])
        lower.append(rates[len(lower)] - lo if np.isfinite(lo) else 0.0)
        upper.append(hi - rates[len(upper)] if np.isfinite(hi) else 0.0)
    fig, axis = plt.subplots(figsize=(8, 4.5))
    colours = [plt.get_cmap("tab10")(index) for index in range(len(names))]
    axis.bar(names, rates, color=colours, yerr=np.asarray([lower, upper]), capsize=4, alpha=0.85)
    for index, row in enumerate(aggregates):
        axis.text(index, min(1.02, rates[index] + 0.06),
                  f"{row['successes']}/{row['completed']}", ha="center", va="bottom", fontsize=9)
    axis.set_ylim(0, 1.08)
    axis.set_ylabel("Task success rate")
    axis.set_title("Counterfactual condition success rate (95% Wilson interval)")
    axis.grid(axis="y", alpha=0.25)
    fig.tight_layout()
    fig.savefig(directory / "success_rate.png", dpi=160)
    plt.close(fig)


def analyze(path, *, threshold_cm: float = 2.0, consecutive: int = 3,
            pair_limit: int = 10, interactive: bool = False, output_dir=None):
    if threshold_cm <= 0 or consecutive < 1 or pair_limit < 0:
        raise ValueError("Invalid threshold, consecutive count or pair limit")
    if interactive:
        try:
            __import__("plotly.graph_objects")
        except ImportError as error:
            raise RuntimeError("Interactive HTML requires plotly; omit --interactive if it is unavailable") from error
    import matplotlib
    matplotlib.use("Agg")
    from matplotlib import pyplot as plt

    summary_path, summary = _load_summary(pathlib.Path(path))
    directory = pathlib.Path(output_dir) if output_dir else summary_path.parent / "counterfactual_analysis"
    directory.mkdir(parents=True, exist_ok=True)
    condition_names = [condition["name"] for condition in summary["conditions"]]
    if tuple(condition_names) != CONDITIONS:
        raise ValueError(f"Expected conditions {CONDITIONS}, got {condition_names}")
    colours = {name: plt.get_cmap("tab10")(index % 10) for index, name in enumerate(condition_names)}

    entries = []
    lookup = {}
    excluded = []
    seen = set()
    for record in summary.get("records", []):
        key = (record["condition"], record["repeat_index"])
        if key in seen:
            raise ValueError(f"Duplicate condition/repeat: {key}")
        seen.add(key)
        if record["condition"] not in condition_names:
            raise ValueError(f"Unknown condition {record['condition']}")
        if record.get("outcome") not in _base.STYLES:
            excluded.append({"condition": key[0], "repeat_index": key[1],
                             "reason": record.get("outcome"), "error": record.get("error")})
            continue
        trace = _base.load_trace(summary_path.parent, record)
        entries.append((record, trace))
        lookup[key] = (record, trace)

    configured_repeats = int(summary["config"]["repeats_per_condition"])
    aggregates = []
    for condition in condition_names:
        group = [record for record in summary.get("records", []) if record["condition"] == condition]
        counts = collections.Counter(record.get("outcome") for record in group)
        completed = counts["success"] + counts["failure"]
        aggregates.append({
            "condition": condition,
            "successes": counts["success"],
            "failures": counts["failure"],
            "errors": counts["error"],
            "interrupted": counts["interrupted"],
            "missing_runs": configured_repeats - len(group),
            "completed": completed,
            "success_rate": counts["success"] / completed if completed else None,
        })

    paired = []
    pair_details = []
    unpaired = []
    plotted = collections.Counter()
    for record, trace in entries:
        if record["condition"] == "clean":
            continue
        reference = lookup.get(("clean", record["repeat_index"]))
        if reference is None:
            unpaired.append({"condition": record["condition"], "repeat_index": record["repeat_index"],
                             "reason": "missing completed clean episode"})
            continue
        clean_record, clean_trace = reference
        fields, series = _base.paired_metrics(
            clean_record, record, clean_trace, trace,
            threshold_m=threshold_cm / 100.0, consecutive=consecutive,
        )
        paired.append((fields, series))
        pair_details.append(fields)
        if plotted[record["condition"]] < pair_limit:
            _base.pair_plot(
                clean_record, record, clean_trace, trace, fields, series,
                colours, directory, threshold_cm / 100.0,
            )
            plotted[record["condition"]] += 1

    if entries:
        config = summary["config"]
        title = (
            f"{config['task_suite_name']} task {config['task_id']} | "
            f"initial state {config['initial_state_id']} | target {config['target_object'] or 'default'}"
        )
        _base.overview_plots(entries, colours, directory, title)
        if interactive:
            _base.interactive_plot(entries, colours, directory)
        _copy_with_name(directory, "trajectories_3d.png", "counterfactual_trajectories_3d.png")
        _copy_with_name(directory, "trajectory_projections.png", "counterfactual_trajectory_projections.png")
    if paired:
        _base.separation_plot(paired, colours, directory)
        _copy_with_name(directory, "separation_vs_time.png", "counterfactual_separation_vs_time.png")

    mask_rows = _mask_rows(summary_path, summary.get("records", []))
    _write_csv(directory / "condition_outcomes.csv", aggregates)
    _write_csv(directory / "paired_trajectory_metrics.csv", pair_details)
    _write_csv(directory / "target_mask_visibility.csv", mask_rows)
    time_rows = []
    for fields, series in paired:
        for index, step in enumerate(series["steps"]):
            time_rows.append({
                "condition": fields["condition"],
                "repeat_index": fields["repeat_index"],
                "clean_outcome": fields["clean_outcome"],
                "counterfactual_outcome": fields["delayed_outcome"],
                "step": int(step),
                **{
                    key: float(values[index])
                    for key, values in series.items() if key != "steps"
                },
            })
    _write_csv(directory / "paired_distance_by_step.csv", time_rows)
    _plot_mask_visibility(mask_rows, directory)
    _plot_success_rate(aggregates, directory)

    report = {
        "experiment": EXPERIMENT,
        "source_summary": str(summary_path),
        "conditions": aggregates,
        "pairs": pair_details,
        "excluded_runs": excluded,
        "unpaired_runs": unpaired,
        "interpretation": [
            "The four conditions change policy pixels only; the physical MuJoCo state remains untouched.",
            "object_only is current background plus the delayed visible target mask/pixels.",
            "context_only is delayed background plus the current visible target mask/pixels.",
            "EEF paths are simulator measurements; dashed lines indicate task failure.",
            "Pairwise separation is descriptive and does not by itself prove which visual factor caused failure.",
            "Success rate denominators contain completed success/failure episodes; errors and interruptions are reported separately.",
            "Mask-empty intervals mean the target was not visible in that camera, so no object pixels could be substituted.",
        ],
        "separation_rule": {
            "threshold_cm": threshold_cm,
            "consecutive_samples": consecutive,
            "meaning": "first sustained EEF positional separation, not a proven causal onset",
        },
    }
    target = directory / "counterfactual_analysis.json"
    target.write_text(json.dumps(report, indent=2, allow_nan=False), encoding="utf-8")
    return target


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("path", type=pathlib.Path, help="Run directory or summary.json")
    parser.add_argument("--threshold-cm", type=float, default=2.0)
    parser.add_argument("--consecutive", type=int, default=3)
    parser.add_argument("--pair-limit", type=int, default=10)
    parser.add_argument("--interactive", action="store_true")
    parser.add_argument("--output-dir", type=pathlib.Path)
    print(analyze(**vars(parser.parse_args())))
