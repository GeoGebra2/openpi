def _write_csv(path: pathlib.Path, rows: list[dict]) -> None:
    if not rows:
        return
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def _load_summary(path: pathlib.Path) -> tuple[pathlib.Path, dict]:
    summary_path = path / "summary.json" if path.is_dir() else path
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    if summary.get("experiment") != EXPERIMENT or summary.get("schema_version") != SCHEMA_VERSION:
        raise ValueError("Requires a target-pose-delay summary generated by the matching runner")
    return summary_path, summary


def _wilson(successes: int, completed: int, z: float = 1.96) -> tuple[float, float]:
    if completed <= 0:
        return float("nan"), float("nan")
    p = successes / completed
    denominator = 1 + z * z / completed
    centre = (p + z * z / (2 * completed)) / denominator
    radius = z * np.sqrt(p * (1 - p) / completed + z * z / (4 * completed * completed)) / denominator
    return max(0.0, centre - radius), min(1.0, centre + radius)


def _success_plot(aggregates: list[dict], directory: pathlib.Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    from matplotlib import pyplot as plt

    rates = [row["success_rate"] if row["success_rate"] is not None else 0.0 for row in aggregates]
    lower, upper = [], []
    for index, row in enumerate(aggregates):
        lo, hi = _wilson(row["successes"], row["completed"])
        lower.append(rates[index] - lo if np.isfinite(lo) else 0.0)
        upper.append(hi - rates[index] if np.isfinite(hi) else 0.0)
    fig, axis = plt.subplots(figsize=(8, 4.5))
    axis.bar([row["condition"] for row in aggregates], rates,
             yerr=np.asarray([lower, upper]), capsize=4,
             color=[plt.get_cmap("tab10")(index) for index in range(len(aggregates))])
    for index, row in enumerate(aggregates):
        axis.text(index, min(1.02, rates[index] + 0.06),
                  f"{row['successes']}/{row['completed']}", ha="center", fontsize=9)
    axis.set_ylim(0, 1.08)
    axis.set_ylabel("Task success rate")
    axis.set_title("Target-pose counterfactual success rate (95% Wilson interval)")
    axis.grid(axis="y", alpha=0.25)
    fig.tight_layout()
    fig.savefig(directory / "success_rate.png", dpi=160)
    plt.close(fig)


def _pose_rows(summary_path: pathlib.Path, records: list[dict]) -> list[dict]:
    rows = []
    for record in records:
        if record.get("outcome") not in ("success", "failure"):
            continue
        trace_path = summary_path.parent / record["trace_path"]
        with np.load(trace_path, allow_pickle=False) as archive:
            values = np.asarray(
                archive["pose_diagnostics"] if "pose_diagnostics" in archive.files else np.empty((0, 19)),
                dtype=float,
            )
            steps = np.asarray(archive["query_steps"], dtype=int)
        if values.shape != (len(steps), 19):
            raise ValueError(f"Invalid pose_diagnostics shape in {trace_path}: {values.shape}")
        for step, value in zip(steps, values):
            rows.append({
                "condition": record["condition"], "repeat_index": record["repeat_index"], "step": int(step),
                "current_object_x": float(value[0]), "current_object_y": float(value[1]), "current_object_z": float(value[2]),
                "delayed_object_x": float(value[3]), "delayed_object_y": float(value[4]), "delayed_object_z": float(value[5]),
                "current_eef_x": float(value[6]), "current_eef_y": float(value[7]), "current_eef_z": float(value[8]),
                "delayed_eef_x": float(value[9]), "delayed_eef_y": float(value[10]), "delayed_eef_z": float(value[11]),
                "stale_render_object_x": float(value[12]), "stale_render_object_y": float(value[13]), "stale_render_object_z": float(value[14]),
                "stale_render_quat_x": float(value[15]), "stale_render_quat_y": float(value[16]),
                "stale_render_quat_z": float(value[17]), "stale_render_quat_w": float(value[18]),
                "delayed_world_object_distance_m": float(np.linalg.norm(value[0:3] - value[3:6])),
                "stale_render_vs_current_object_distance_m": float(np.linalg.norm(value[0:3] - value[12:15])),
            })
    return rows


def _pose_plot(rows: list[dict], directory: pathlib.Path) -> None:
    if not rows:
        return
    import matplotlib
    matplotlib.use("Agg")
    from matplotlib import pyplot as plt

    grouped: dict[str, list[dict]] = collections.defaultdict(list)
    for row in rows:
        grouped[row["condition"]].append(row)
    fig, axes = plt.subplots(2, 1, figsize=(10, 7), sharex=True)
    for index, condition in enumerate(CONDITIONS):
        values = grouped.get(condition, [])
        if not values:
            continue
        by_step: dict[int, list[float]] = collections.defaultdict(list)
        for row in values:
            by_step[row["step"]].append(row["delayed_world_object_distance_m"] * 100)
        steps = sorted(by_step)
        axes[0].plot(steps, [np.median(by_step[step]) for step in steps],
                     color=plt.get_cmap("tab10")(index), label=condition)
        if condition == "target_pose_stale":
            rendered_by_step: dict[int, list[float]] = collections.defaultdict(list)
            for row in values:
                rendered_by_step[row["step"]].append(row["stale_render_vs_current_object_distance_m"] * 100)
            axes[1].plot(sorted(rendered_by_step),
                         [np.median(rendered_by_step[step]) for step in sorted(rendered_by_step)],
                         color=plt.get_cmap("tab10")(index), label=condition)
    axes[0].set_ylabel("Delayed vs current target (cm)")
    axes[0].set_title("Target displacement measured at policy queries")
    axes[1].set_ylabel("Rendered stale vs current target (cm)")
    axes[1].set_xlabel("Environment step")
    for axis in axes:
        axis.grid(alpha=0.25)
        axis.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(directory / "target_pose_displacement.png", dpi=160)
    plt.close(fig)


def analyze(path, *, threshold_cm: float = 2.0, consecutive: int = 3,
            pair_limit: int = 10, interactive: bool = False, output_dir=None):
    if threshold_cm <= 0 or consecutive < 1 or pair_limit < 0:
        raise ValueError("Invalid threshold, consecutive count or pair limit")
    if interactive:
        try:
            __import__("plotly.graph_objects")
        except ImportError as error:
            raise RuntimeError("Interactive HTML requires plotly; omit --interactive if unavailable") from error
    import matplotlib
    matplotlib.use("Agg")
    from matplotlib import pyplot as plt

    summary_path, summary = _load_summary(pathlib.Path(path))
    directory = pathlib.Path(output_dir) if output_dir else summary_path.parent / "target_pose_analysis"
    directory.mkdir(parents=True, exist_ok=True)
    condition_names = [condition["name"] for condition in summary["conditions"]]
    if tuple(condition_names) != CONDITIONS:
        raise ValueError(f"Expected conditions {CONDITIONS}, got {condition_names}")
    colours = {name: plt.get_cmap("tab10")(index % 10) for index, name in enumerate(condition_names)}
    entries, lookup, seen, excluded = [], {}, set(), []
    for record in summary.get("records", []):
        key = (record["condition"], record["repeat_index"])
        if key in seen:
            raise ValueError(f"Duplicate condition/repeat: {key}")
        seen.add(key)
        if record.get("outcome") not in _base.STYLES:
            excluded.append({"condition": key[0], "repeat_index": key[1],
                             "reason": record.get("outcome"), "error": record.get("error")})
            continue
        trace = _base.load_trace(summary_path.parent, record)
        entries.append((record, trace))
        lookup[key] = (record, trace)

    configured_repeats = int(summary["config"]["repeats_per_condition"])
    aggregates = []
    for condition in condition_names:
        records = [record for record in summary.get("records", []) if record["condition"] == condition]
        counts = collections.Counter(record.get("outcome") for record in records)
        completed = counts["success"] + counts["failure"]
        aggregates.append({
            "condition": condition, "successes": counts["success"], "failures": counts["failure"],
            "errors": counts["error"], "interrupted": counts["interrupted"],
            "missing_runs": configured_repeats - len(records), "completed": completed,
            "success_rate": counts["success"] / completed if completed else None,
        })

    paired, pair_details, unpaired = [], [], []
    plotted = collections.Counter()
    for record, trace in entries:
        if record["condition"] == "clean":
            continue
        reference = lookup.get(("clean", record["repeat_index"]))
        if reference is None:
            unpaired.append({"condition": record["condition"], "repeat_index": record["repeat_index"],
                             "reason": "missing completed clean episode"})
            continue
        clean_record, clean_trace = reference
        fields, series = _base.paired_metrics(
            clean_record, record, clean_trace, trace,
            threshold_m=threshold_cm / 100.0, consecutive=consecutive,
        )
        paired.append((fields, series))
        pair_details.append(fields)
        if plotted[record["condition"]] < pair_limit:
            _base.pair_plot(clean_record, record, clean_trace, trace, fields, series,
                            colours, directory, threshold_cm / 100.0)
            plotted[record["condition"]] += 1

    if entries:
        config = summary["config"]
        title = (f"{config['task_suite_name']} task {config['task_id']} | initial state "
                 f"{config['initial_state_id']} | target {config['target_object'] or 'default'}")
        _base.overview_plots(entries, colours, directory, title)
        if interactive:
            _base.interactive_plot(entries, colours, directory)
    if paired:
        _base.separation_plot(paired, colours, directory)
    pose_rows = _pose_rows(summary_path, summary.get("records", []))
    _write_csv(directory / "condition_outcomes.csv", aggregates)
    _write_csv(directory / "paired_trajectory_metrics.csv", pair_details)
    _write_csv(directory / "target_pose_queries.csv", pose_rows)
    time_rows = []
    for fields, series in paired:
        for index, step in enumerate(series["steps"]):
            time_rows.append({
                "condition": fields["condition"], "repeat_index": fields["repeat_index"],
                "clean_outcome": fields["clean_outcome"], "counterfactual_outcome": fields["delayed_outcome"],
                "step": int(step), **{key: float(values[index]) for key, values in series.items() if key != "steps"},
            })
    _write_csv(directory / "paired_distance_by_step.csv", time_rows)
    _success_plot(aggregates, directory)
    _pose_plot(pose_rows, directory)
    report = {
        "experiment": EXPERIMENT, "source_summary": str(summary_path), "conditions": aggregates,
        "pairs": pair_details, "excluded_runs": excluded, "unpaired_runs": unpaired,
        "interpretation": [
            "target_pose_stale changes only the rendered target world pose; physical simulation state is restored before every action.",
            "full_delay is the complete selected-camera image from the delayed environment step.",
            "The target is rendered using current camera/robot/scene geometry, so no pixel inpainting is used.",
            "EEF separation is descriptive; it does not alone prove a causal failure onset.",
            "Success rates exclude errors and interruptions from the denominator and include Wilson intervals in the plot.",
        ],
        "separation_rule": {"threshold_cm": threshold_cm, "consecutive_samples": consecutive,
                            "meaning": "first sustained EEF separation, not a proven causal onset"},
    }
    target = directory / "target_pose_analysis.json"
    target.write_text(json.dumps(report, indent=2, allow_nan=False), encoding="utf-8")
    return target


